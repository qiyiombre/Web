export async function getAiCache(cacheKey) {
  const row = await one('SELECT value_json AS "valueJson" FROM ai_cache WHERE cache_key = $1', [cacheKey]);
  if (!row) {
    return null;
  }
  try {
    const value = JSON.parse(row.valueJson);
    await pool.query('UPDATE ai_cache SET last_used_at = now() WHERE cache_key = $1', [cacheKey]);
    return value;
  } catch {
    await pool.query('DELETE FROM ai_cache WHERE cache_key = $1', [cacheKey]);
    return null;
  }
}

