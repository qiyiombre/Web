export async function createDomainCategory({ mapId, name, color, keywords }) {
  await ensureDomainCategoriesInitialized(mapId);
  const cleanName = normalizeDomainCategoryName(name);
  const cleanColor = normalizeColor(color) ?? colorForTag(cleanName);
  const cleanKeywords = normalizeKeywords(keywords);
  if (!cleanName) {
    throw new Error('领域大类名称不能为空');
  }
  const duplicate = await one('SELECT id FROM domain_categories WHERE map_id = $1 AND name = $2', [mapId, cleanName]);
  if (duplicate) {
    throw new Error('同一星云图下已有这个领域大类');
  }
  const orderRow = await one('SELECT COALESCE(MAX(sort_order), -1) + 1 AS "nextOrder" FROM domain_categories WHERE map_id = $1', [mapId]);
  const inserted = await one(
    `INSERT INTO domain_categories (map_id, name, color, keywords_json, sort_order, updated_at)
     VALUES ($1, $2, $3, $4, $5, now())
     RETURNING id`,
    [mapId, cleanName, cleanColor, JSON.stringify(cleanKeywords), Number(orderRow?.nextOrder ?? 0)]
  );
  await touchDomainCategoryState(mapId);
  return getDomainCategoryById(inserted.id);
}

