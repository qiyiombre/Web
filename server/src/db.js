export async function deleteTag(id) {
  const existing = await getTagById(id);
  if (!existing) {
    return { deleted: false, reason: 'not-found' };
  }

  const exclusive = await one(
    `SELECT COUNT(*)::int AS count
     FROM logs l
     JOIN log_tags target ON target.log_id = l.id AND target.tag_id = $1
     LEFT JOIN log_tags other ON other.log_id = l.id AND other.tag_id <> $1
     WHERE other.tag_id IS NULL`,
    [id]
  );

  if (exclusive.count > 0) {
    throw new Error(`不能删除「${existing.name}」，有 ${exclusive.count} 篇日志只关联了这个标签。请先给这些日志添加其他标签。`);
  }

  await pool.query('DELETE FROM tags WHERE id = $1', [id]);
  return { deleted: true };
}

export async function restoreTagSnapshot(snapshot) {
  const mapId = Number(snapshot?.mapId);
  if (!Number.isFinite(mapId) || mapId <= 0) {
    throw new Error('标签快照无效');
  }

  const tagId = await withTransaction(async (client) => {
    const tag = await ensureRestoredTag(mapId, snapshot, client);
    const logIds = Array.isArray(snapshot?.logIds) ? snapshot.logIds : [];
    for (const rawLogId of logIds) {
      const logId = Number(rawLogId);
      if (!Number.isFinite(logId) || logId <= 0) {
        continue;
      }
      const log = await getLogById(logId);
      if (log?.mapId === mapId) {
        await client.query('INSERT INTO log_tags (log_id, tag_id, weight) VALUES ($1, $2, 1) ON CONFLICT DO NOTHING', [logId, tag.id]);
      }
    }
    return tag.id;
  });
  return getTagById(tagId);
}

