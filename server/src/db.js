async function ensureRestoredTag(mapId, snapshot, client) {
  const tagId = Number(snapshot?.id);
  const cleanName = normalizeTagName(snapshot?.name);
  const cleanColor = normalizeColor(snapshot?.color) ?? colorForTag(cleanName);
  if (!cleanName) {
    throw new Error('标签名称不能为空');
  }

  if (Number.isFinite(tagId) && tagId > 0) {
    const existingById = await getTagById(tagId);
    if (existingById) {
      if (existingById.mapId !== mapId) {
        throw new Error('标签 ID 已被其他星云图使用');
      }
      return existingById;
    }
  }

  const duplicate = await one('SELECT id FROM tags WHERE map_id = $1 AND name = $2', [mapId, cleanName], client);
  if (duplicate) {
    return { id: duplicate.id, mapId, name: cleanName, color: cleanColor };
  }

  if (Number.isFinite(tagId) && tagId > 0) {
    await client.query('INSERT INTO tags (id, map_id, name, color) VALUES ($1, $2, $3, $4)', [tagId, mapId, cleanName, cleanColor]);
    await syncIdentitySequence('tags', client);
    return { id: tagId, mapId, name: cleanName, color: cleanColor };
  }

  const inserted = await one('INSERT INTO tags (map_id, name, color) VALUES ($1, $2, $3) RETURNING id', [mapId, cleanName, cleanColor], client);
  return { id: inserted.id, mapId, name: cleanName, color: cleanColor };
}

async function currentTimestamp(client = pool) {
  const row = await one('SELECT now()::text AS value', [], client);
  return row.value;
}

function restoredTimestamp(value, fallback) {
  return String(value ?? '').trim() || fallback;
}

function colorForTag(name) {
  const palette = ['#62d6ff', '#f7d774', '#ff8fa3', '#8cf0b4', '#b99cff', '#ffb86b', '#7dd3fc', '#c4f36a'];
  let hash = 0;
  for (let i = 0; i < name.length; i += 1) {
    hash = (hash * 31 + name.charCodeAt(i)) >>> 0;
  }
  return palette[hash % palette.length];
}

async function syncIdentitySequence(table, client) {
  await client.query(`SELECT setval(pg_get_serial_sequence('${table}', 'id'), GREATEST((SELECT COALESCE(MAX(id), 1) FROM ${table}), 1), true)`);
}

async function withTransaction(callback) {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const result = await callback(client);
    await client.query('COMMIT');
    return result;
  } catch (error) {
    await client.query('ROLLBACK').catch(() => {});
    throw error;
  } finally {
    client.release();
  }
}

async function all(sql, params = [], client = pool) {
  const result = await client.query(sql, params);
  return result.rows;
}

async function one(sql, params = [], client = pool) {
  const result = await client.query(sql, params);
  return result.rows[0] ?? null;
}
