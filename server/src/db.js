export async function initializeDatabase() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS users (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      username TEXT NOT NULL UNIQUE,
      password_hash TEXT NOT NULL,
      password_salt TEXT NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );

    CREATE TABLE IF NOT EXISTS sessions (
      token TEXT PRIMARY KEY,
      user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      expires_at BIGINT NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );

    CREATE TABLE IF NOT EXISTS user_preferences (
      user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
      preferences_json TEXT NOT NULL DEFAULT '{}',
      updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );

    CREATE TABLE IF NOT EXISTS nebula_maps (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      name TEXT NOT NULL,
      description TEXT NOT NULL DEFAULT '',
      created_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );

    CREATE TABLE IF NOT EXISTS logs (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      map_id INTEGER NOT NULL REFERENCES nebula_maps(id) ON DELETE CASCADE,
      title TEXT NOT NULL,
      content TEXT NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );

    CREATE TABLE IF NOT EXISTS tags (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      map_id INTEGER NOT NULL REFERENCES nebula_maps(id) ON DELETE CASCADE,
      name TEXT NOT NULL,
      color TEXT NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      UNIQUE (map_id, name)
    );

    CREATE TABLE IF NOT EXISTS log_tags (
      log_id INTEGER NOT NULL REFERENCES logs(id) ON DELETE CASCADE,
      tag_id INTEGER NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
      weight REAL NOT NULL DEFAULT 1,
      PRIMARY KEY (log_id, tag_id)
    );

    CREATE TABLE IF NOT EXISTS ai_cache (
      cache_key TEXT PRIMARY KEY,
      value_json TEXT NOT NULL,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      last_used_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );

    CREATE TABLE IF NOT EXISTS domain_category_state (
      map_id INTEGER PRIMARY KEY REFERENCES nebula_maps(id) ON DELETE CASCADE,
      initialized INTEGER NOT NULL DEFAULT 0,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );

    CREATE TABLE IF NOT EXISTS domain_categories (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      map_id INTEGER NOT NULL REFERENCES nebula_maps(id) ON DELETE CASCADE,
      name TEXT NOT NULL,
      color TEXT NOT NULL,
      keywords_json TEXT NOT NULL DEFAULT '[]',
      sort_order INTEGER NOT NULL DEFAULT 0,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      UNIQUE (map_id, name)
    );

    CREATE INDEX IF NOT EXISTS idx_nebula_maps_user_id ON nebula_maps(user_id);
    CREATE INDEX IF NOT EXISTS idx_sessions_user_id ON sessions(user_id);
    CREATE INDEX IF NOT EXISTS idx_logs_map_id ON logs(map_id);
    CREATE INDEX IF NOT EXISTS idx_logs_map_created_at ON logs(map_id, created_at DESC);
    CREATE INDEX IF NOT EXISTS idx_log_tags_tag_id ON log_tags(tag_id);
    CREATE INDEX IF NOT EXISTS idx_tags_map_id ON tags(map_id);
    CREATE INDEX IF NOT EXISTS idx_ai_cache_last_used_at ON ai_cache(last_used_at);
    CREATE INDEX IF NOT EXISTS idx_domain_categories_map_id ON domain_categories(map_id);
  `);

  await deleteExpiredSessions();
  await deleteStaleAiCache();
  await seedIfEmpty();
}

export async function createUser(username, password) {
  const cleanUsername = normalizeUsername(username);
  validateCredentials(cleanUsername, password);

  const existing = await one('SELECT id FROM users WHERE username = $1', [cleanUsername]);
  if (existing) {
    throw new Error('用户名已存在');
  }

  const salt = randomBytes(16).toString('hex');
  const hash = hashPassword(password, salt);
  const inserted = await one(
    'INSERT INTO users (username, password_hash, password_salt) VALUES ($1, $2, $3) RETURNING id',
    [cleanUsername, hash, salt]
  );
  return getUserById(inserted.id);
}

export async function verifyUserCredentials(username, password) {
  const cleanUsername = normalizeUsername(username);
  const row = await one(
    `SELECT
       id,
       username,
       password_hash AS "passwordHash",
       password_salt AS "passwordSalt",
       created_at::text AS "createdAt"
     FROM users
     WHERE username = $1`,
    [cleanUsername]
  );
  if (!row || !password) {
    return null;
  }

  if (!passwordMatches(row, password)) {
    return null;
  }

  return publicUser(row);
}

export async function updateUserPassword(userId, currentPassword, newPassword) {
  const row = await one(
    `SELECT
       id,
       username,
       password_hash AS "passwordHash",
       password_salt AS "passwordSalt"
     FROM users
     WHERE id = $1`,
    [userId]
  );
  if (!row || !passwordMatches(row, currentPassword)) {
    return false;
  }

  validatePassword(newPassword);
  const salt = randomBytes(16).toString('hex');
  const hash = hashPassword(newPassword, salt);
  await pool.query('UPDATE users SET password_hash = $1, password_salt = $2 WHERE id = $3', [hash, salt, userId]);
  return true;
}

